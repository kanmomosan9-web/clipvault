def kana_key(text: str) -> str:
    """表記ゆれを吸収した照合キーを作る。

    ひらがな→カタカナ、小書き→大書き、濁点・半濁点の除去、長音と中黒の削除。
    「ゼラス」と「セラス」、「リー・シン」と「リーシン」を同一視するため。
    """
    s = unicodedata.normalize("NFKC", text)
    s = "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)
    s = s.translate(_SMALL)
    for a, b in _FOLD:
        s = s.replace(a, b)
    return re.sub(r"[ー・\s]", "", s).upper()


