def display_form(term: str) -> str:
    """公式表記の中黒・スペースを落とす。

    「リー・シン」「ミス フォーチュン」は公式名だが、人が検索するときは
    「リーシン」「ミスフォーチュン」と打つ。検索一致を優先する。
    """
    return re.sub(r"[・\s]", "", term)


_INDEX = {}
for _t in ALL_TERMS:
    _INDEX.setdefault(kana_key(_t), display_form(_t))

_PROTECTED_KEYS = {kana_key(_t) for _t in PROTECTED}


def build_prompt(limit_chars: int = 170, extra: list[str] | None = None) -> str:
    """initial_prompt を組み立てる。長すぎると幻覚を招くので文字数で打ち切る。"""
    terms, total = [], 0
    for t in (extra or []) + PROMPT_TERMS:
        if t in terms:
            continue
        if total + len(t) + 1 > limit_chars:
            break
        terms.append(t)
        total += len(t) + 1
    return "、".join(terms)


def _min_ratio(n: int) -> float:
    """短い語ほど厳しく。3文字以下は完全一致のみ許す。"""
    if n <= 3:
        return 1.01
    if n <= 5:
        return 0.75
    return 0.80


def prompt_for(game: str) -> str:
    """ゲームに応じた initial_prompt を組み立てる。

    LoL/TFT はチャット履歴由来の高頻度語を使う。それ以外は
    config.GAME_PROMPTS にフォールバック。どちらも呼び名を先頭に置く。
    """
    import config

    if game in config.VOCAB_GAMES:
        return build_prompt(config.PROMPT_MAX_CHARS, extra=MEMBERS)
    body = config.BASE_PROMPT + config.GAME_PROMPTS.get(game, "")
    names = "、".join(MEMBERS)
    return (names + ("、" + body if body else ""))[:config.PROMPT_MAX_CHARS]


def uses_correction(game: str) -> bool:
    import config
    return game in config.VOCAB_GAMES and config.VOCAB_CORRECT


def correct(text: str, threshold: float | None = None) -> tuple[str, list[tuple[str, str]]]:
    """認識結果のカタカナ語を既知の語彙に寄せる。

    完全一致は即置換、そうでなければ音の近さで最も近い語を探す。
    固有名詞（チャンピオン名など）の微妙な誤認識を救うのが目的。
    """
    fixes = []

    def fix(m: re.Match) -> str:
        word = m.group(0)
        if len(word) < 3:
            return word
        key = kana_key(word)
        if key in _PROTECTED_KEYS:
            return word
        hit = _INDEX.get(key)
        if hit:
            if hit != word:
                fixes.append((word, hit))
            return hit
        floor = threshold if threshold is not None else _min_ratio(len(key))
        best, score = None, floor - 1e-9
        for k, term in _INDEX.items():
            if abs(len(k) - len(key)) > 1:
                continue
            r = SequenceMatcher(None, key, k).ratio()
            if r > score:
                best, score = term, r
        if best:
            fixes.append((word, best))
            return best
        return word

    return re.sub(f"[{_KATA}]{{3,}}", fix, text), fixes
